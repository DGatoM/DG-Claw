falhas = []
contados = [0]


def confere(nome, obtido, esperado):
    contados[0] += 1
    if obtido == esperado:
        print(f"  ✓ {nome}")
    else:
        print(f"  ✗ {nome}\n      esperado: {esperado!r}\n      obtido:   {obtido!r}")
        falhas.append(nome)


def escrever(linhas):
    """Grava um transcript de mentira e devolve o caminho."""
    f = tempfile.NamedTemporaryFile("w", suffix=".jsonl", delete=False, encoding="utf-8")
    for o in linhas:
        f.write(json.dumps(o) + "\n")
    f.close()
    return f.name


def user(texto, ts="2026-08-10T12:00:00Z", meta=False):
    return {"type": "user", "timestamp": ts, "isMeta": meta,
            "message": {"content": [{"type": "text", "text": texto}]}}


def tool(nome, entrada, ts="2026-08-10T12:00:01Z", id=None):
    bloco = {"type": "tool_use", "name": nome, "input": entrada}
    if id:
        bloco["id"] = id
    return {"type": "assistant", "timestamp": ts, "message": {"content": [bloco]}}


def resultado(id, erro, ts="2026-08-10T12:00:02Z"):
    return {"type": "user", "timestamp": ts,
            "message": {"content": [{"type": "tool_result", "tool_use_id": id, "is_error": erro, "content": "x"}]}}


def texto_de(eventos):
    return [(e["origin"], e.get("via"), e["text"]) for e in eventos]


