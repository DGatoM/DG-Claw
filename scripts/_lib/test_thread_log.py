#!/usr/bin/env python3
"""test_thread_log.py — A bancada do extrator da conversa (Fase B).

Roda sem agente vivo, sem rede e sem sujar a máquina: monta transcripts de mentira
num diretório temporário e confere o que sai. É o teste que protege a peça mais fácil
de quebrar em silêncio, porque um extrator errado não dá erro nenhum: ele só devolve
uma conversa a menos, e ninguém percebe até a pessoa reclamar que "sumiu mensagem".

    python3 test_thread_log.py
"""
import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import thread_log as tl  # noqa: E402

falhas = []
contados = [0]


def confere(nome, obtido, esperado):
    contados[0] += 1
    if obtido == esperado:
        print(f"  ✓ {nome}")
    else:
        print(f"  ✗ {nome}\n      esperado: {esperado!r}\n      obtido:   {obtido!r}")
        falhas.append(nome)


def escrever(linhas):
    """Grava um transcript de mentira e devolve o caminho."""
    f = tempfile.NamedTemporaryFile("w", suffix=".jsonl", delete=False, encoding="utf-8")
    for o in linhas:
        f.write(json.dumps(o) + "\n")
    f.close()
    return f.name


def user(texto, ts="2026-08-10T12:00:00Z", meta=False):
    return {"type": "user", "timestamp": ts, "isMeta": meta,
            "message": {"content": [{"type": "text", "text": texto}]}}


def tool(nome, entrada, ts="2026-08-10T12:00:01Z"):
    return {"type": "assistant", "timestamp": ts,
            "message": {"content": [{"type": "tool_use", "name": nome, "input": entrada}]}}


def texto_de(eventos):
    return [(e["origin"], e.get("via"), e["text"]) for e in eventos]


CANAL = '<channel source="plugin:telegram:telegram" user="Danilo">'

print("\n1. o canal do painel (<dgchat>), que é o padrão")
p = escrever([
    user('<dgchat from="Marta" chat="c_ana" msg="1" ts="2026-08-10T12:00:00Z">bom dia</dgchat>'),
    tool("mcp__dgchat__reply", {"chat": "c_ana", "text": "bom dia, Marta"}),
])
confere("entrada e saída do painel entram na lista",
        texto_de(tl.build_thread_log(p)),
        [("owner", "plataforma", "bom dia"), ("persona-direct", "plataforma", "bom dia, Marta")])

print("\n2. o Telegram continua funcionando (não-regressão)")
p = escrever([
    user(CANAL + "e aí?</channel>", meta=True),
    tool("mcp__telegram__telegram__reply", {"text": "tudo certo"}),
])
confere("entrada e saída do Telegram entram na lista",
        texto_de(tl.build_thread_log(p)),
        [("owner", "telegram", "e aí?"), ("persona-direct", "telegram", "tudo certo")])

print("\n3. as duas origens na MESMA lista, em ordem")
p = escrever([
    user(CANAL + "pelo Telegram</channel>", ts="2026-08-10T12:00:00Z", meta=True),
    tool("mcp__telegram__telegram__reply", {"text": "respondi no Telegram"}, ts="2026-08-10T12:00:01Z"),
    user('<dgchat from="Marta" chat="c_ana" msg="2" ts="x">pelo site</dgchat>', ts="2026-08-10T12:00:02Z"),
    tool("mcp__dgchat__reply", {"chat": "c_ana", "text": "respondi no site"}, ts="2026-08-10T12:00:03Z"),
])
confere("a conversa vem inteira, na ordem em que aconteceu",
        [e["via"] for e in tl.build_thread_log(p)],
        ["telegram", "telegram", "plataforma", "plataforma"])

print("\n4. o que NÃO pode entrar na conversa")
p = escrever([
    user("leia /tmp/dgclaw-poke-ana-heartbeat-20260810-120000.txt e execute"),
    tool("mcp__dgchat__reply", {"chat": "c_ana", "text": "terminei a ronda"}),
    user("Stop hook feedback: você não respondeu"),
    user("[Request interrupted by user]"),
    user("Caveat: The messages below were generated by the user while running a command"),
    tool("Read", {"file_path": "/etc/passwd"}),
    tool("mcp__dgchat__reply", {"chat": "c_ana", "text": "pronto"}),
])
eventos = tl.build_thread_log(p)
confere("poke de cron, recado do sistema e ferramenta ficam de fora",
        [e["text"] for e in eventos], ["terminei a ronda", "pronto"])
confere("a fala puxada por cron é marcada como 'por conta própria'",
        eventos[0]["origin"], "persona-cron")
confere("o recado do sistema NÃO transforma a resposta seguinte em fala espontânea",
        eventos[1]["origin"], "persona-cron")

print("\n5. o envelope mal formado não derruba nada")
p = escrever([
    user('<dgchat from="Marta" msg="1">sem o chat, isto não é envelope válido</dgchat>'),
    user('<dgchat from="Marta" chat="c_ana" msg="2" ts="x">com aspas " e <sinal></dgchat>'),
    {"type": "user", "timestamp": "2026-08-10T12:00:03Z", "message": {"content": []}},
])
confere("envelope sem chat é ignorado, e o bom passa",
        [e["text"] for e in tl.build_thread_log(p)], ['com aspas " e <sinal>'])

print("\n6. o corpo com a tag de fechamento escapada volta ao original")
p = escrever([
    user('<dgchat from="Marta" chat="c_ana" msg="1" ts="x">olha esse texto: <\\/dgchat> aqui</dgchat>'),
])
confere("o escape é desfeito na leitura",
        [e["text"] for e in tl.build_thread_log(p)], ["olha esse texto: </dgchat> aqui"])

print("\n7. arquivo entregue vira mensagem com legenda")
p = escrever([
    user('<dgchat from="Marta" chat="c_ana" msg="1" ts="x">manda o relatório</dgchat>'),
    tool("mcp__dgchat__send_file", {"chat": "c_ana", "path": "/opt/dgclaw/ana/arquivos/r.pdf",
                                    "caption": "o relatório de agosto"}),
    tool("mcp__dgchat__send_file", {"chat": "c_ana", "path": "/opt/dgclaw/ana/arquivos/s.pdf"}),
])
eventos = [e for e in tl.build_thread_log(p) if e.get("tipo") == "arquivo"]
confere("com legenda, mostra a legenda", eventos[0]["text"], "o relatório de agosto")
confere("sem legenda, mostra o nome do arquivo", eventos[1]["text"], "[arquivo: s.pdf]")
confere("o caminho do arquivo vem junto", eventos[0]["arquivo"], "/opt/dgclaw/ana/arquivos/r.pdf")

print("\n8. o filtro por conversa")
p = escrever([
    user('<dgchat from="A" chat="c_um" msg="1" ts="x">da conversa um</dgchat>'),
    tool("mcp__dgchat__reply", {"chat": "c_um", "text": "resposta um"}),
    user('<dgchat from="B" chat="c_dois" msg="1" ts="x">da conversa dois</dgchat>'),
    tool("mcp__dgchat__reply", {"chat": "c_dois", "text": "resposta dois"}),
    user(CANAL + "do Telegram</channel>", meta=True),
])
confere("--chat traz só a conversa pedida, e não mistura o Telegram",
        [e["text"] for e in tl.build_thread_log(p, chat="c_um")],
        ["da conversa um", "resposta um"])

print("\n9. o teto de mensagens conta do fim para trás")
p = escrever([
    x for i in range(10)
    for x in (user(f'<dgchat from="C" chat="c_x" msg="{i}" ts="x">msg {i}</dgchat>'),)
])
confere("last=3 devolve as três últimas",
        [e["text"] for e in tl.build_thread_log(p, last=3)], ["msg 7", "msg 8", "msg 9"])
confere("last=0 devolve tudo", len(tl.build_thread_log(p, last=0)), 10)

print("\n10. arquivo que não existe não estoura")
confere("transcript ausente vira lista vazia, não exceção",
        tl.build_thread_log("/tmp/nao-existe-mesmo-12345.jsonl"), [])

print(f"\n{contados[0] - len(falhas)}/{contados[0]} verdes.")
if falhas:
    print("REPROVADO: " + ", ".join(falhas))
    sys.exit(1)
print("APROVADO")
