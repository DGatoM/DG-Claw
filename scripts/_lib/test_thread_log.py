"""test_thread_log.py — A bancada do extrator da conversa (Fase B).

Roda sem agente vivo, sem rede e sem sujar a máquina: monta transcripts de mentira
num diretório temporário e confere o que sai. É o teste que protege a peça mais fácil
de quebrar em silêncio, porque um extrator errado não dá erro nenhum: ele só devolve
uma conversa a menos, e ninguém percebe até a pessoa reclamar que "sumiu mensagem".

    python3 test_thread_log.py
"""
import json
